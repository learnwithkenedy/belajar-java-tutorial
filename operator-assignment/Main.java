public class Main {
    public static void main(String[] args) {

        // ini adalah assignment =

        int x = 10;
        // Nilai Awal
        System.out.println("ini adalah nilai x adalah : " + x);

        // Penjumlahan
        x += 10;
        System.out.println("ini adalah nilai += x adalah : " + x);

        // Pengurangan
        x -= 10;
        System.out.println("ini adalah nilai -= x adalah : " + x);

        // Pembagian
        x /= 10;
        System.out.println("ini adalah nilai /= x adalah : " + x);

        // Modulus
        x %= 10;
        System.out.println("ini adalah nilai %= x adalah : " + x);
    }    
}
